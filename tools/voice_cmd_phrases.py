#!/usr/bin/env python3
"""Writes firmware/voice_cmd_phrases.h: the watch's offline voice commands
(voice_sr.cpp) with their MultiNet7 phonemes.

MultiNet7 English matches phonemes, not letters. ESP-SR turns text into
them on the watch with a built-in English pronouncer (flite) that is
~620 KB of code - more than the app partition has left - so they're
worked out here instead, from the CMU pronouncing dictionary, with the
same symbol map as esp-sr's tool/multinet_g2p.py.

    pip install cmudict
    python3 tools/voice_cmd_phrases.py

Add or change a phrase below and run it again. Command names are the
VoiceCmd values in voice_sr.cpp.
"""
import os
import sys

import cmudict

# (command, phrase); the timers are added below
PHRASES = [
    ("CMD_TIME", "what time is it"), ("CMD_TIME", "tell me the time"),
    ("CMD_NEXT", "next song"), ("CMD_NEXT", "skip song"), ("CMD_NEXT", "next track"),
    ("CMD_PREV", "previous song"), ("CMD_PREV", "previous track"),
    ("CMD_PAUSE", "pause music"), ("CMD_PAUSE", "stop music"), ("CMD_PAUSE", "pause the music"),
    ("CMD_PLAY", "play music"), ("CMD_PLAY", "resume music"),
    ("CMD_VOL_UP", "volume up"), ("CMD_VOL_UP", "turn it up"),
    ("CMD_VOL_DOWN", "volume down"), ("CMD_VOL_DOWN", "turn it down"),
    ("CMD_TIMER_CANCEL", "cancel the timer"), ("CMD_TIMER_CANCEL", "stop the timer"),
    ("CMD_FIND_PHONE", "find my phone"), ("CMD_FIND_PHONE", "where is my phone"),
    ("CMD_DND_ON", "turn on do not disturb"), ("CMD_DND_ON", "do not disturb"),
    ("CMD_DND_OFF", "turn off do not disturb"),
    ("CMD_HOME", "go home"), ("CMD_HOME", "show the watch face"),
    ("CMD_SETTINGS", "open settings"),
    ("CMD_NOTIFICATIONS", "show notifications"), ("CMD_NOTIFICATIONS", "open notifications"),
    ("CMD_RECORDER", "open the recorder"), ("CMD_RECORDER", "record a memo"),
    ("CMD_SLEEP", "open sleep tracking"),
    ("CMD_MUSIC", "open music"),
    ("CMD_ASSISTANT", "open the assistant"), ("CMD_ASSISTANT", "ask a question"),
]
TIMER_MINUTES = [
    (1, "one minute"), (2, "two minutes"), (3, "three minutes"), (4, "four minutes"),
    (5, "five minutes"), (10, "ten minutes"), (15, "fifteen minutes"), (20, "twenty minutes"),
    (25, "twenty five minutes"), (30, "thirty minutes"), (45, "forty five minutes"),
    (60, "one hour"), (90, "an hour and a half"), (120, "two hours"),
]
for minutes, words in TIMER_MINUTES:
    PHRASES.append((f"CMD_TIMER + {minutes}", f"set a timer for {words}"))
    PHRASES.append((f"CMD_TIMER + {minutes}", f"timer {words}"))

# esp-sr tool/multinet_g2p.py
ALPHABET = {"AE1": "a", "N": "N", " ": " ", "OW1": "b", "V": "V", "AH0": "c", "L": "L", "F": "F", "EY1": "d", "S": "S",
            "B": "B", "R": "R", "AO1": "e", "D": "D", "AH1": "c", "EH1": "f", "OW0": "b", "IH0": "g", "G": "G", "HH": "h",
            "K": "K", "IH1": "g", "W": "W", "AY1": "i", "T": "T", "M": "M", "Z": "Z", "DH": "j", "ER0": "k", "P": "P",
            "NG": "l", "IY1": "m", "AA1": "n", "Y": "Y", "UW1": "o", "IY0": "m", "EH2": "f", "CH": "p", "AE0": "a",
            "JH": "q", "ZH": "r", "AA2": "n", "SH": "s", "AW1": "t", "OY1": "u", "AW2": "t", "IH2": "g", "AE2": "a",
            "EY2": "d", "ER1": "k", "TH": "v", "UH1": "w", "UW2": "o", "OW2": "b", "AY2": "i", "UW0": "o", "AH2": "c",
            "EH0": "f", "AW0": "t", "AO2": "e", "AO0": "e", "UH0": "w", "UH2": "w", "AA0": "n", "AY0": "i", "IY2": "m",
            "EY0": "d", "ER2": "k", "OY2": "u", "OY0": "u"}


def phonemes(phrase, d):
    words = []
    for w in phrase.split():
        prons = d.get(w)
        if not prons:
            sys.exit(f"'{w}' isn't in the dictionary: spell it differently")
        words.append("".join(ALPHABET[p] for p in prons[0]))
    return " ".join(words)


def main():
    d = cmudict.dict()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "voice_cmd_phrases.h")
    lines = [
        "// Generated by tools/voice_cmd_phrases.py - edit the phrases there.",
        "// The watch's offline voice commands and their MultiNet7 phonemes (voice_sr.cpp).",
        "#pragma once",
        "static const CmdPhrase CMD_PHRASES[] = {",
    ]
    for cmd, text in PHRASES:
        lines.append(f'    {{ {cmd}, "{text}", "{phonemes(text, d)}" }},')
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(PHRASES)} phrases -> {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
